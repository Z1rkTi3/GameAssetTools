CATALOGS = {"en_US": {message: message for message in RU}, "ru_RU": RU}


def translate(message: str, language: str = "en_US", **values) -> str:
    """Translate a UI message, falling back to English for unknown keys/locales.

    Named values are interpolated verbatim *after* lookup. Callers retain the
    English source and values so an interface redraw can change language without
    mutating their data. No formatting is attempted when no values are supplied.
    """
    template = CATALOGS.get(language, CATALOGS["en_US"]).get(message, message)
    return template.format(**values) if values else template
